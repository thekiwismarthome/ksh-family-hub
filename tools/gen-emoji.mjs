const clean = e => e.replace(/️/g, '');

const out = [];
const seen = new Set();
for (const e of data) {
  if (e.group === undefined || !(e.group in GROUP_OF)) continue;
  if (e.version > 14) continue;
  const key = clean(e.emoji);
  if (seen.has(key)) continue;
  seen.add(key);
  const words = [...new Set([e.label, ...(e.tags || [])].join(' ').toLowerCase().split(/[\s,]+/).filter(w => w.length > 1))];
  const extra = EXTRA[key] || EXTRA[e.emoji];
  if (extra) for (const w of extra.split(' ')) if (!words.includes(w)) words.push(w);
  out.push([e.emoji, words.join(' '), GROUP_OF[e.group]]);
}
const src = `// GENERATED by tools/gen-emoji.mjs from emojibase-data (Unicode CLDR). Do not edit by hand.
// GROUPS: [icon, name]; EMOJI: [emoji, search words, group index]
export const GROUPS = ${JSON.stringify(GROUPS)};
export const EMOJI = ${JSON.stringify(out)};
`;
writeFileSync(new URL('../src/hub/emoji-data.js', import.meta.url), src);
